// 层：功能
#pragma once
#include <QString>

// ai/chat — 轻量 Markdown → HTML 转换器（方向62：助手回复排版）。
//
// 方言子集（宁小勿大，无人值守自行定案；不支持的语法按原文显示，不猜意图）：
//   块级：ATX 标题（# ~ ######）、围栏代码块（``` 围栏，语言标注忽略）、
//         无序/有序列表（单层，`- `/`* `/`1. ` 起头）、
//         管道表格（首行表头 + `|---|---|` 分隔行 + 数据行）
//   行内：**粗体**、*斜体*、`行内代码`
//   段落：空行分段，段内换行保持
// 明确不支持（原样显示）：嵌套列表、引用块、链接/图片、setext 标题、
// 删除线、任务列表、HTML 直插。
//
// 安全纪律（硬约束）：整个输入先做 HTML 转义，之后再做标记替换——
// 不存在「用户或模型文本以裸 HTML 进入结果」的通路；转换器只生成
// 自己白名单里的标签。
namespace AiMarkdown {
// 输入按不可信文本处理；返回可交给 QTextDocument::insertHtml 的片段。
QString toHtml(const QString &markdown);
}
