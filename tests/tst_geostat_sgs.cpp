  SgsParams params;

  VariogramModel zeroSill = model;
  zeroSill.nugget = 0;
  zeroSill.sill = 0;
  QVERIFY( sgs( samples, grid, zeroSill, params ).status == Status::InvalidInput );
  QVERIFY( sgs( {}, grid, model, params ).status == Status::InvalidInput );

